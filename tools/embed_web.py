"""Generate the firmware's gzip web asset, including before PlatformIO builds."""

import argparse
import gzip
import io
from pathlib import Path


if __name__ == "__main__":
    PROJECT_ROOT = Path(__file__).resolve().parent.parent
else:
    Import("env")
    PROJECT_ROOT = Path(env["PROJECT_DIR"])
SOURCE = PROJECT_ROOT / "web" / "index.html"
HEADER = PROJECT_ROOT / "src" / "logic" / "web_index_html.h"


def render_header():
    html = SOURCE.read_text(encoding="utf-8").encode("utf-8")
    buffer = io.BytesIO()
    with gzip.GzipFile(filename="", mode="wb", fileobj=buffer, mtime=0) as output:
        output.write(html)
    payload = buffer.getvalue()
    lines = [
        "#pragma once",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "// Generated by tools/embed_web.py from web/index.html; do not edit.",
        f"// Gzipped size: {len(payload)} bytes",
        "static const uint8_t INDEX_HTML_GZ[] = {",
    ]
    for offset in range(0, len(payload), 16):
        lines.append("    " + ", ".join(f"0x{byte:02x}" for byte in payload[offset:offset + 16]) + ",")
    lines.extend(["};", "", "static const size_t INDEX_HTML_GZ_LEN = sizeof(INDEX_HTML_GZ);", ""])
    return "\n".join(lines)


def generate(check=False):
    content = render_header()
    if HEADER.exists() and HEADER.read_text(encoding="utf-8") == content:
        return 0
    if check:
        print("Embedded web page is stale; run python tools/embed_web.py")
        return 1
    HEADER.write_text(content, encoding="utf-8", newline="\n")
    print(f"Updated {HEADER.relative_to(PROJECT_ROOT)}")
    return 0


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the embedded page needs regeneration.")
    raise SystemExit(generate(parser.parse_args().check))
else:
    # PlatformIO executes this file as a pre-build SCons script.
    generate()
